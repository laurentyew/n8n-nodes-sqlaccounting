const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', 'contract', 'operations.json');
const out = path.join(__dirname, '..', 'nodes', 'SqlAccounting', 'registry.generated.ts');

function generate() {
	const reg = JSON.parse(fs.readFileSync(src, 'utf8'));
	const resources = reg.resources.map((r) => ({
		resource: r.resource,
		name: r.name,
		pathParam: r.path_param,
		kind: r.kind,
		group: r.group || null,
		ops: typeof r.ops === 'string' ? reg.ops_sets[r.ops] : r.ops,
		verifyGet: Boolean(r.verify_get),
		verifyEndpoint: Boolean(r.verify_endpoint),
	}));
	return [
		'// GENERATED by scripts/gen-registry.js from contract/operations.json. Do not edit.',
		`export const CONTRACT_VERSION = ${reg.contract_version};`,
		`export const PAGE_SIZE = ${reg.page_size};`,
		"export type PathParamType = 'CODE' | 'DOCKEY' | 'AUTOKEY' | null;",
		"export type OpName = 'list' | 'get' | 'create' | 'update' | 'delete';",
		"export type ResourceKind = 'master' | 'transactional' | 'report';",
		'export interface RegistryEntry {',
		'\tresource: string; name: string; pathParam: PathParamType; kind: ResourceKind;',
		'\tgroup: string | null; ops: OpName[]; verifyGet: boolean; verifyEndpoint: boolean;',
		'}',
		`export const REGISTRY: RegistryEntry[] = ${JSON.stringify(resources, null, '\t')};`,
		'',
	].join('\n');
}

if (require.main === module) {
	fs.writeFileSync(out, generate());
	console.log('wrote', out);
}

module.exports = { generate, out };
